#!/usr/bin/env python3
"""odo's look in one place: ui/tokens.json, written out for both apps.

    tools/tokens.py           write app/.../ui/Tokens.kt and desktop/tokens.h
    tools/tokens.py --check   fail if either is not what tokens.json makes (for CI, or before a release)
"""
import json, os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KT = os.path.join(root, "app/src/main/java/com/patrickreynolds/mpeinstruments/ui/Tokens.kt")
H = os.path.join(root, "desktop/tokens.h")
COLOURS = ["ink", "panel", "panelHigh", "line", "text", "textDim"]
SIGNALS = ["warn", "danger"]
HEAD = "Generated by tools/tokens.py from ui/tokens.json: change that file and run the tool, not this one."


def num(v):
    return ("%g" % v)


def kotlin(t):
    out = ["// " + HEAD, "package com.patrickreynolds.mpeinstruments.ui", "",
           "import androidx.compose.ui.graphics.Color", "import androidx.compose.ui.unit.dp", "import androidx.compose.ui.unit.sp", "",
           "/** odo's look, shared with odo for computers (desktop/tokens.h). */", "object Tokens {"]
    for name, p in t["palettes"].items():
        out.append("    val %s = Palette(" % name)
        for k in COLOURS:
            out.append("        %s = Color(0xFF%s)," % (k, p[k]))
        out.append("        parts = listOf(%s)," % ", ".join("Color(0xFF%s)" % c for c in p["parts"]))
        for k in SIGNALS:
            out.append("        %s = Color(0xFF%s)," % (k, p[k]))
        out.append("        eink = %s," % ("true" if p["eink"] else "false"))
        out.append("    )")
    out.append("    object Type {")
    for k, v in t["type"].items():
        out.append("        val %s = %s.sp" % (k, num(v)))
    out.append("    }")
    out.append("    object Radius {")
    for k, v in t["radius"].items():
        out.append("        val %s = %s.dp" % (k, num(v)))
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def cpp(t):
    out = ["// " + HEAD, "// odo's look, shared with odo on Android (ui/Tokens.kt). Colours are 0xRRGGBBAA.",
           "#pragma once", "#include <cstdint>", "", "namespace tokens {", "",
           "struct Palette {",
           "    uint32_t %s;" % ", ".join(COLOURS),
           "    uint32_t parts[4];",
           "    uint32_t %s;" % ", ".join(SIGNALS),
           "    bool eink;",
           "};", ""]
    for name, p in t["palettes"].items():
        vals = ", ".join("0x%sFFu" % p[k] for k in COLOURS)
        parts = ", ".join("0x%sFFu" % c for c in p["parts"])
        sig = ", ".join("0x%sFFu" % p[k] for k in SIGNALS)
        out.append("inline constexpr Palette %s{%s, {%s}, %s, %s};" % (name, vals, parts, sig, "true" if p["eink"] else "false"))
    out += ["", "// The same colour at alpha a (0..255).",
            "constexpr uint32_t alpha(uint32_t c, uint32_t a) { return (c & 0xFFFFFF00u) | (a & 0xFFu); }", "",
            "namespace type {"]
    for k, v in t["type"].items():
        out.append("inline constexpr float %s = %s;" % (k, num(v)))
    out += ["}  // namespace type", "", "namespace radius {"]
    for k, v in t["radius"].items():
        out.append("inline constexpr float %s = %s;" % (k, num(v)))
    out += ["}  // namespace radius", "", "}  // namespace tokens"]
    return "\n".join(out) + "\n"


def main():
    with open(os.path.join(root, "ui/tokens.json")) as f:
        t = json.load(f)
    want = {KT: kotlin(t), H: cpp(t)}
    if "--check" in sys.argv:
        stale = [p for p, s in want.items() if not os.path.exists(p) or open(p).read() != s]
        for p in stale:
            print("out of date: %s (run tools/tokens.py)" % os.path.relpath(p, root), file=sys.stderr)
        sys.exit(1 if stale else 0)
    for p, s in want.items():
        with open(p, "w") as f:
            f.write(s)
        print(os.path.relpath(p, root))


if __name__ == "__main__":
    main()
